"""Golden-file regression tests for the CSV → merge → score → aggregate pipeline.

The golden values are hand-derived from the accepted formula text
(SI = 0.4375·ccs + 0.3125·eav + 0.25·cpr; eav = min(1, |ln r| / ln 2)) in
docs/decisions/0005-golden-file-batch-oracles.md — never regenerated by
running the code. Any future formula- or schema-changing ADR must regenerate
this file with values hand-derived in that ADR (full schema: appended columns
arrive with their own value oracles).
"""

from pathlib import Path

import pandas as pd
import pandas.testing as pdt

from ecds_shock_index import ShockIndexCalculator
from ecds_shock_index.data_loader import (
    load_cms_measure_weights,
    load_ncqa_ecds,
    merge_ecds_and_weights,
)

REPO = Path(__file__).resolve().parents[1]
GOLDEN_PATH = REPO / "tests" / "golden" / "example_scored_golden.csv"


def _score_examples() -> pd.DataFrame:
    ecds = load_ncqa_ecds(REPO / "data" / "raw" / "example_ncqa_ecds.csv")
    weights = load_cms_measure_weights(REPO / "data" / "raw" / "example_cms_measure_weights.csv")
    return ShockIndexCalculator().score_dataframe(merge_ecds_and_weights(ecds, weights))


def test_score_dataframe_matches_golden():
    result = _score_examples()
    golden = pd.read_csv(GOLDEN_PATH)
    # Full schema, pinned column order — appended columns must fail here
    # until the golden is regenerated with their own hand-derived oracles.
    assert list(result.columns) == list(golden.columns)
    pdt.assert_frame_equal(result, golden, atol=1e-9, rtol=0)


def test_aggregate_contract_matches_golden():
    summary = ShockIndexCalculator().aggregate_contract(_score_examples())
    # weighted = (0.1195763554 + 0.5027665313 + 3·0.3020323512)/5 = 0.3056879881
    # mean = 0.9243752379/3 = 0.3081250793; both rounded to 4 dp by the API.
    assert summary == {
        "weighted_shock_index": 0.3057,
        "mean_shock_index": 0.3081,
        "max_shock_index": 0.5028,
        "measure_count": 3,
        "risk_tier": "moderate",
    }
